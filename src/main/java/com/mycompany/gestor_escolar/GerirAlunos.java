    private void carregarAlunos() {
        String sql = "SELECT aluno_id, nome_aluno, media FROM aluno WHERE turma_id = ?";

        DefaultTableModel modelo = (DefaultTableModel) tblAlunos.getModel();

        modelo.setRowCount(0);

        try (Connection conn = Conexao.Ligacao(); PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setInt(1, this.idturma);
            ResultSet rs = stmt.executeQuery();
            if (rs.isBeforeFirst()) {

                while (rs.next()) {
                    int id = rs.getInt("aluno_id");
                    String nome = rs.getString("nome_aluno");
                    float media = rs.getFloat("media");

                    modelo.addRow(new Object[]{
                        id,
                        nome,
                        media
                    });
                }
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar Alunos: " + e.getMessage());
        }
    }

